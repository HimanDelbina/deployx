# 6. BuildKit rawjson Parsing
# ==============================================================================
def test_buildkit_rawjson_parsing():
    parser = BuildKitParser()

    # Rawjson event with vertex name
    json_event1 = json.dumps({
        "vertex": {
            "name": "[5/8] RUN pip install --no-cache-dir -r requirements.txt",
            "digest": "sha256:12345",
        }
    })
    parser.parse_line(json_event1)
    assert parser.step_current == 5
    assert parser.step_total == 8
    assert parser.approx_percent == 62
    assert "pip install" in parser.current_operation
    assert parser.is_network_operation() is True

    # Rawjson with statuses
    json_event2 = json.dumps({
        "statuses": [
            {
                "id": "step-6",
                "name": "[6/8] COPY . /app/",
                "current": 6,
                "total": 8,
            }
        ]
    })
    parser.parse_line(json_event2)
    assert parser.step_current == 6
    assert parser.step_total == 8
    assert "COPY" in parser.current_operation

    # Rawjson with base64 encoded log data
    encoded_log = base64.b64encode(b"Collecting requests==2.31.0\nDownloading requests.whl").decode("utf-8")
    json_event3 = json.dumps({
        "logs": [
            {"vertex": "sha256:123", "data": encoded_log}
        ]
    })
    parser.parse_line(json_event3)
    assert any("Collecting requests" in l for l in parser.last_relevant_lines)


