# 7. Current Build Step Display & Stall Warning Context
# ==============================================================================
def test_build_step_visibility_and_stall_context():
    console = Console(record=True)
    reporter = DeploymentProgressReporter(
        "herbal_web",
        console=console,
        python_index="https://user:mypassword@mirrors.aliyun.com/pypi/simple/",
    )

    # Stream a rawjson line
    raw_step = json.dumps({"vertex": {"name": "[5/8] RUN pip install --no-cache-dir -r requirements.txt"}})
    reporter.on_build_output(raw_step)

    output = console.export_text()
    assert "Build step 5/8" in output or "Step 5/8" in output
    assert "RUN pip install" in output

    # Trigger stall warning
    reporter.on_stall(elapsed=125.0, idle=120.0)
    stall_output = console.export_text()

    assert "WARNING:" in stall_output
    assert "120 seconds" in stall_output
    assert "Current build step:" in stall_output
    assert "RUN pip install --no-cache-dir -r requirements.txt" in stall_output
    assert "Possible network/package index issue." in stall_output
    assert "Configured Python index:" in stall_output
    assert "Custom (https://user:***@mirrors.aliyun.com/pypi/simple/)" in stall_output
    assert "mypassword" not in stall_output


