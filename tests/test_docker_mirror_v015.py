# 3. Project Config Mirror Persistence & Environment Override Priority
# ==============================================================================
def test_project_mirror_config_and_env_override(monkeypatch):
    # Default behavior: unset
    cfg_default = ProjectConfig(
        project=ProjectMeta(name="testproj"),
        git=GitConfig(repository="https://github.com/company/myapp.git"),
    )
    assert resolve_build_environment(cfg_default) == {}

    # Config set: project level
    cfg_custom = ProjectConfig(
        project=ProjectMeta(name="testproj"),
        git=GitConfig(repository="https://github.com/company/myapp.git"),
        build=BuildConfig(
            python=PythonBuildConfig(
                index_url="https://mirrors.aliyun.com/pypi/simple/",
                extra_index_url="https://extra.mirror.com/simple/",
                trusted_host="mirrors.aliyun.com",
            )
        ),
    )
    env_resolved = resolve_build_environment(cfg_custom)
    assert env_resolved["PIP_INDEX_URL"] == "https://mirrors.aliyun.com/pypi/simple/"
    assert env_resolved["PIP_EXTRA_INDEX_URL"] == "https://extra.mirror.com/simple/"
    assert env_resolved["PIP_TRUSTED_HOST"] == "mirrors.aliyun.com"

    # Environment override priority: os.environ > config
    monkeypatch.setenv("PIP_INDEX_URL", "https://override.mirror.com/simple/")
    env_overridden = resolve_build_environment(cfg_custom)
    assert env_overridden["PIP_INDEX_URL"] == "https://override.mirror.com/simple/"
    # Unoverridden extra still comes from config
    assert env_overridden["PIP_EXTRA_INDEX_URL"] == "https://extra.mirror.com/simple/"


