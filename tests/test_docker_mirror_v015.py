# 11. Network Precheck Function
# ==============================================================================
def test_package_index_precheck_handling(mocker):
    # Success case
    mocker.patch("urllib.request.urlopen", return_value=MagicMock(__enter__=MagicMock(return_value=MagicMock(status=200))))
    ok, msg = check_package_index_reachability("https://mirrors.aliyun.com/pypi/simple/")
    assert ok is True
    assert "Reachable" in msg

    # Failure case: does not crash
    mocker.patch("urllib.request.urlopen", side_effect=Exception("Connection timed out"))
    ok_fail, msg_fail = check_package_index_reachability("https://unreachable.mirror.xyz/")
    assert ok_fail is False
    assert "Connection timed out" in msg_fail
