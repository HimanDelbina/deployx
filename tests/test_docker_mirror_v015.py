# 5. DeployX-Owned File Regeneration vs User-Owned Protection
# ==============================================================================
def test_deployx_file_regeneration_and_user_protection(tmp_path):
    generated_file = tmp_path / "Dockerfile.deployx"
    generated_file.write_text(
        "# ==============================================================================\n"
        "# Auto-generated by DeployX for testproj\n"
        "# ==============================================================================\n"
        "FROM python:3.12-slim\n",
        encoding="utf-8",
    )
    assert is_deployx_generated_file(generated_file) is True

    user_file = tmp_path / "Dockerfile"
    user_file.write_text("FROM python:3.11-alpine\n# Handcrafted by developer\n", encoding="utf-8")
    assert is_deployx_generated_file(user_file) is False

    modified_file = tmp_path / "custom_dockerfile.deployx"
    modified_file.write_text("FROM ubuntu:24.04\nRUN apt update\n", encoding="utf-8")
    assert is_deployx_generated_file(modified_file) is False


