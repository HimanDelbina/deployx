# 1. Generated Dockerfile PIP_INDEX_URL Support & Deterministic Layer
# ==============================================================================
def test_generated_dockerfile_pip_support_and_deterministic_layer(tmp_path):
    config = ProjectConfig(
        project=ProjectMeta(name="myweb"),
        git=GitConfig(repository="https://github.com/myteam/myweb.git"),
    )
    # Case 1: Requirements without gunicorn declared
    detection = DetectionResult(
        framework=FrameworkType.DJANGO,
        confidence=1.0,
        matched_indicators=["requirements.txt"],
        infrastructure=DetectedInfrastructure(
            has_dockerfile=False,
            dependencies=["django", "psycopg2"],
            has_gunicorn=False,
        ),
    )
    df_path = tmp_path / "Dockerfile.deployx"
    generate_django_dockerfile(config, detection, df_path)

    content = df_path.read_text(encoding="utf-8")
    # Verify ARGs
    assert "ARG PIP_INDEX_URL" in content
    assert "ARG PIP_EXTRA_INDEX_URL" in content
    assert "ARG PIP_TRUSTED_HOST" in content
    assert "Auto-generated by DeployX for myweb" in content
    # Verify deterministic single layer with gunicorn appended
    assert "pip install --no-cache-dir -r requirements.txt;" in content
    assert "&& pip install --no-cache-dir gunicorn" in content

    # Case 2: Requirements with gunicorn already declared
    detection_with_gunicorn = DetectionResult(
        framework=FrameworkType.DJANGO,
        confidence=1.0,
        matched_indicators=["requirements.txt"],
        infrastructure=DetectedInfrastructure(
            has_dockerfile=False,
            dependencies=["django", "gunicorn"],
            has_gunicorn=True,
        ),
    )
    df_path2 = tmp_path / "Dockerfile_gunicorn.deployx"
    generate_django_dockerfile(config, detection_with_gunicorn, df_path2)
    content2 = df_path2.read_text(encoding="utf-8")
    assert "pip install --no-cache-dir -r requirements.txt;" in content2
    # Gunicorn should not be appended separately
    assert "&& pip install --no-cache-dir gunicorn" not in content2


