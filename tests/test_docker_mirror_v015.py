# 4. Credential Redaction in URLs and Logs
# ==============================================================================
def test_credential_redaction_urls_and_text():
    url_with_creds = "https://myuser:secretpass123@mirror.example.com/pypi/simple/"
    redacted = redact_url_credentials(url_with_creds)
    assert redacted == "https://myuser:***@mirror.example.com/pypi/simple/"
    assert "secretpass123" not in redacted

    token_url = "http://my_auth_token@internal.mirror.local/simple"
    redacted_token = redact_url_credentials(token_url)
    assert redacted_token == "http://***@internal.mirror.local/simple"
    assert "my_auth_token" not in redacted_token

    log_entry = (
        "Running: pip install --index-url https://admin:super_secret@pypi.company.com/simple/ requests\n"
        "DATABASE_PASSWORD=production_secret_pw\n"
    )
    redacted_log = redact_sensitive_text(log_entry)
    assert "super_secret" not in redacted_log
    assert "production_secret_pw" not in redacted_log
    assert "https://admin:***@pypi.company.com/simple/" in redacted_log


